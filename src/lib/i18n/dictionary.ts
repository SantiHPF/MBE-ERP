export const DICTIONARIES: Record<Locale, Dictionary> = { EN: en, ES: es };

/** Looks up a dotted key and fills {0}, {1}… placeholders. */
export function translate(
  dict: Dictionary,
  key: string,
  ...args: (string | number)[]
): string {
  const value = key
    .split(".")
    .reduce<unknown>((node, part) => (node as Record<string, unknown>)?.[part], dict);

  if (typeof value !== "string") return key;
  return args.reduce<string>(
    (text, arg, i) => text.replaceAll(`{${i}}`, String(arg)),
    value,
  );
}
